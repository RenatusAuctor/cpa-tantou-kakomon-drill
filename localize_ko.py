# コメントは開発者向けなので日本語のまま残す（半端に訳すと読めなくなる）
COMMENT = re.compile(r"/\*.*?\*/|(?<![:'\"])//[^\n]*", re.S)


def translate(s):
    parts, last, n = [], 0, 0
    for m in COMMENT.finditer(s):
        chunk = s[last:m.start()]
        for a, b in PAIRS:
            if a in chunk:
                n += chunk.count(a)
                chunk = chunk.replace(a, b)
        parts.append(chunk)
        parts.append(m.group(0))          # コメントはそのまま
        last = m.end()
    chunk = s[last:]
    for a, b in PAIRS:
        if a in chunk:
            n += chunk.count(a)
            chunk = chunk.replace(a, b)
    parts.append(chunk)
    return "".join(parts), n


def main():
    for f in ("kakomon_template.html", "checklist_template.html", "sync.js"):
        s = open(f, encoding="utf-8").read()
        s, n = translate(s)
        open(f, "w", encoding="utf-8").write(s)
        print(f"  {f}: {n} 置換")


if __name__ == "__main__":
    main()
